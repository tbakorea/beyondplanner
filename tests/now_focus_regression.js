const assert=require('node:assert/strict'),fs=require('node:fs');
const source=fs.readFileSync(require('node:path').join(__dirname,'../dashboard/app.js'),'utf8');
const fn=source.match(/function buildNowFocusRecommendation\([^\n]*\{\n[\s\S]*?\n\}/)[0];
const recommend=new Function(fn+';return buildNowFocusRecommendation;')();
const tasks=[{id:'b',text:'보통 업무',priority:'B'},{id:'a',text:'중요 업무',priority:'A'},{id:'done',text:'완료 업무',priority:'A',resolved:true}];
const before=JSON.stringify(tasks);
assert.equal(recommend(tasks,[],540).id,'a');
assert.equal(recommend(tasks,[],540).minutes,25);
assert.equal(recommend(tasks,[{slot:'09:20',text:'회의',start:560,end:620}],540).minutes,15);
assert.equal(recommend(tasks,[{slot:'09:10',text:'회의',start:550,end:610}],540).kind,'schedule');
assert.equal(recommend(tasks,[{slot:'09:00',text:'회의',start:540,end:600}],550).title,'회의');
assert.equal(recommend(tasks,[{slot:'09:00',text:'종료된 회의',start:540,end:600}],600).id,'a');
assert.equal(recommend([{text:'위임 업무',resolved:true}],[],540).kind,'empty');
assert.equal(recommend([{text:'  '}],[],540).kind,'empty');
assert.equal(recommend([{text:'신규 A',priority:'A'},{text:'이월 A',priority:'A',carried:true}],[],540).title,'이월 A');
assert.equal(JSON.stringify(tasks),before);
console.log('10 now-focus recommendation checks passed');
